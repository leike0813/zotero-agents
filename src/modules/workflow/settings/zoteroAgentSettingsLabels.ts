/**
 * Resolves the configured locale for every static key, published under both its
 * FTL id and its page alias. A key the active locale has not translated is left
 * out of the record, which is what lets the page fall back to readable English.
 */
export function buildZoteroAgentSettingsLabels(): Record<string, string> {
  const resolved = new Map<string, string>();
  for (const key of ZOTERO_AGENT_SETTINGS_LABEL_KEYS) {
    if (parameterized.has(key)) continue;
    const value = getStringOrFallback(key, "");
    if (value) resolved.set(key, value);
  }
  const labels: Record<string, string> = {};
  for (const [key, value] of resolved) labels[key] = value;
  for (const [alias, key] of Object.entries(
    ZOTERO_AGENT_SETTINGS_PAGE_LABEL_ALIASES,
  )) {
    const value = resolved.get(key);
    if (value) labels[alias] = value;
  }
  return labels;
}
