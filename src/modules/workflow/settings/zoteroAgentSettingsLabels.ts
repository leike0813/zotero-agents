/**
 * Label key set and page bridge for the Built-in Agent settings window.
 *
 * The window's visible copy has two names and this module is the only place
 * that joins them:
 *
 * - FTL message ids in `addon/locale/<locale>/addon.ftl`, the single source of
 *   every translated string.
 * - the short camelCase keys the page passes to `text(labels, key, fallback)`
 *   in `src/dashboard/components/ZoteroAgentSettingsControls.tsx`, collected in
 *   `ZOTERO_AGENT_SETTINGS_PAGE_LABEL_ALIASES`.
 *
 * The host projects the active locale through `buildZoteroAgentSettingsLabels()`
 * into the snapshot `labels` record, so a page key resolves without the page
 * knowing an FTL id. Neither side may invent a name of its own: a new visible
 * string means a new FTL key, an entry in the alias table, and a value for it in
 * every locale. An alias that is missing simply stays absent from the record,
 * which makes the page show its own English fallback rather than a wrong string.
 *
 * This module sits with the settings host because that window and the Pi
 * settings graph it composes stay behind the lazy Pi edge; the dashboard page
 * bundle must not import it.
 */

